"""
Generate a default scenery.json for a track (only if it doesn't have one yet).

    tools/.venv/bin/python tools/author_scenery.py austin

Main grandstand and pit building along the start straight, race-control tower, start
gantry, grandstands outside the four slowest corners, footbridges over the two longest
straights, and trees. Generic structures; positions are approximate.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("track")
    ap.add_argument("--force", action="store_true", help="overwrite an existing scenery.json")
    args = ap.parse_args()
    tdir = ROOT / "data" / "tracks" / args.track
    out_file = tdir / "scenery.json"
    if out_file.exists() and not args.force:
        print(f"{args.track}: scenery.json exists, leaving it alone (use --force to regenerate)")
        return
    t = json.loads((tdir / "track.json").read_text())
    L = t["length_m"]
    corners = t["corners"]
    w = lambda x: round(x % L, 1)  # noqa: E731
    stands = [{"s_start": w(L - 260), "s_end": 240, "side": "left", "gap": 4, "rows": 12, "roof": True}]
    for c in sorted(corners, key=lambda c: c["min_radius_m"])[:4]:
        outside = "left" if c["direction"] == "right" else "right"
        stands.append({"s_start": w(c["s_start"] - 20), "s_end": w(c["s_end"] + 20), "side": outside, "gap": 3, "rows": 9, "roof": False})
    # Straights = gaps between corners; bridges over the middle of the two longest.
    gaps = []
    srt = sorted(corners, key=lambda c: c["s_start"])
    for a, b in zip(srt, srt[1:] + srt[:1]):
        gaps.append(((b["s_start"] - a["s_end"]) % L, w(a["s_end"] + ((b["s_start"] - a["s_end"]) % L) / 2)))
    bridges = [{"s": mid} for length, mid in sorted(gaps, reverse=True)[:2] if length > 300]
    scenery = {
        "description": "AUTO-GENERATED by tools/author_scenery.py (generic structures, approximate positions; edit freely).",
        "grandstands": stands,
        "pits": {"s_start": w(L - 200), "s_end": 400, "side": "right", "gap": 1, "depth": 16, "height": 10},
        "towers": [{"s": 150, "side": "right", "gap": 22, "height": 20}],
        "bridges": bridges,
        "gantry": {"s": 0},
        "trees": {"every": 6, "perStation": 3, "minGap": 8, "maxGap": 160, "clearance": 6, "seed": sum(map(ord, args.track))},
    }
    out_file.write_text(json.dumps(scenery, indent=1) + "\n")
    print(f"{args.track}: scenery with {len(stands)} grandstands, {len(bridges)} bridges")


if __name__ == "__main__":
    main()
